"""Player Career: builds ux/flows/mainflow/gamemodes/Liga/Data/PrismProFaces.lua from the user's database.

The faces Create Your Player offers are the PrismYouth host bodies (PrismYouthHosts.lua: players of clubs in leagues
outside the career), grouped by skin tone and listed youngest first, so stepping through a tone shows faces that fit a
young player. Each body keeps its own head, face and hair models in matches (the game has one per player).

The database is read the way libpv's f16_db.c reads it: tables walked in order (an edited database keeps stale
directory offsets), players table "CZUM", player id "ykFq", skin tone "ejir" (stored 0..10, light to dark).
usage: pro_faces.py <fifa_ng_db.db> <PrismYouthHosts.lua> <out PrismProFaces.lua>
"""
import re, struct, sys

db = open(sys.argv[1], 'rb').read()
size = len(db)
le32 = lambda o: struct.unpack_from('<I', db, o)[0]
le16 = lambda o: struct.unpack_from('<H', db, o)[0]


def hdr_ok(off):
    if off + 36 > size:
        return False
    rs, fc = le32(off + 4), le32(off + 24)
    if not rs or rs > 8192 or not fc or fc > 128 or off + 36 + fc * 16 > size:
        return False
    for i in range(fc):
        f = off + 36 + i * 16
        if le32(f) > 16 or any(not (65 <= db[f + k] <= 122) for k in range(8, 12)):
            return False
    return True


def tables():
    tc = le32(0x10)
    names = [db[0x18 + i * 8:0x1c + i * 8].decode('latin1') for i in range(tc)]
    off, out = 0x18 + tc * 8 + 4, {}
    for t in range(tc):
        if not hdr_ok(off):
            break
        rs, written, fc, strl = le32(off + 4), le16(off + 18), le32(off + 24), le32(off + 12)
        fields = {db[off + 36 + i * 16 + 8:off + 36 + i * 16 + 12].decode('latin1'): (le32(off + 36 + i * 16 + 4), le32(off + 36 + i * 16 + 12)) for i in range(fc)}
        out[names[t]] = (off + 36 + fc * 16, rs, written, fields)
        e = off + 36 + fc * 16 + written * rs + strl
        off = next((e + k for k in range(64) if hdr_ok(e + k)), None)
        if off is None:
            break
    return out


def bits(r, bo, depth):
    v = 0
    for i in range(depth):
        b = bo + i
        v |= ((r[b >> 3] >> (b & 7)) & 1) << i
    return v


data, rs, written, F = tables()['CZUM']
tone = {}
for i in range(written):
    r = db[data + i * rs:data + (i + 1) * rs]
    if r[-1] & 0x80:
        continue
    tone[bits(r, *F['ykFq'])] = bits(r, *F['ejir'])

GROUPS = [('Very Light', (0, 1)), ('Light', (2, 3)), ('Light Tan', (4,)), ('Tan', (5, 6)), ('Brown', (7,)),
          ('Dark Brown', (8,)), ('Dark', (9, 10))]
src = open(sys.argv[2], encoding='utf-8').read()
bodies = []
for club, s in re.findall(r'\[(\d+)\] = "([^"]*)"', src):
    for pid, _, yy in re.findall(r'(\d+)([a-zA-Z])(\d\d)', s):
        pid, yy = int(pid), int(yy)
        if pid in tone:
            bodies.append((pid, int(club), 2000 + yy if yy < 40 else 1900 + yy))
lists = []
for _, raw in GROUPS:
    g = sorted((b for b in bodies if tone[b[0]] in raw), key=lambda b: (-b[2], b[0]))
    lists.append(' '.join('%d:%d' % (b[0], b[1]) for b in g))
n = sum(len(l.split()) for l in lists)
with open(sys.argv[3], 'w', encoding='utf-8') as o:
    o.write('-- PrismProFaces - generated by tools/pro_faces.py from the user\'s database; do not edit by hand.\n--\n')
    o.write('-- The faces Create Your Player offers (PrismPro.open): %d PrismYouth host bodies in %d skin tones, youngest first.\n' % (n, len(GROUPS)))
    o.write('-- Data: the global PRISM_PRO_FACES = { n = <bodies>, labels = { <tone name>, ... }, tones = { "<player id>:<club id> ...", ... } }.\n')
    o.write('local T = { n = %d, labels = { %s }, tones = {\n' % (n, ', '.join('"%s"' % g[0] for g in GROUPS)))
    for l in lists:
        o.write('  "%s",\n' % l)
    o.write('} }\nrawset(_G, "PRISM_PRO_FACES", T)\nreturn T\n')
print('faces:', n, [len(l.split()) for l in lists])
