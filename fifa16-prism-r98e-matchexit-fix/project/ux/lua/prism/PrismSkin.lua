-- PrismSkin.lua - draws an existing career screen through Prism Native (FIFA 16 mobile, Lua 5.1).
--
-- Prism Native is libpv's own UI layer: scenes compiled by tools/skinc.js from src/skins/*.skin.js and drawn on the
-- render thread. A skinned screen keeps its own VVM, Lua logic and nav flow; this module mirrors what the screen
-- publishes into the native layer and feeds native taps back into the screen's own action handlers.
--
-- How a screen gets skinned (tools/skinstall.js):
--   * VVM skin: the installer copies the screen's VM to <Vm>__<Id>.lua, ending in
--         return PrismSkin.wrap(Class, Spec, Theme)
--     and appends PrismJobs.lua, this module, PrismTheme.lua and the compiled spec (<Id>.skin.lua) to the copy's .lreq.
--   * Inline skin (Settings: its VVM lives in the OBB and has no .lreq of ours): the patched stock VM finds this module
--     through PRISM_SKIN.module and wraps its own class on first use.
--   * Guest screen (a stock screen that opens over native ones): its VM reports to the global PrismSkinGuest.
--
-- wrap() hands the screen a copy of `init` whose `im` and `nav` are watched: every value the screen publishes is
-- forwarded to the native layer, every action handler it registers can be called from a native tap. The stock layout
-- stays loaded underneath (hidden through bnd_prism_zinc / bnd_prism_native) and comes back by itself whenever native
-- is not available. Failures fall back to the stock layout; every hook into the game's Lua is guarded with pcall.
--
-- Skin spec (one table per screen, generated by skinc from src/skins/<Id>.skin.js; `when` and `model` are Lua members
-- the installer adds):
--   id, scene, depth      the screen's id, its native scene file and stacking depth
--   shell, shellPass      the shared room scene behind it and the bindings forwarded to that scene
--   pass                  stock binding -> native value name(s), forwarded as published
--   values                derived values { name, expr, deps }: Prism expressions re-evaluated when a dependency changes
--   lists                 native lists, fed from an array binding or from numbered slot bindings
--   actions               tap action -> { alias, data, arg } or { nav = event }
--   backEvents, back, backActions, leaveOn   which nav events / actions mean "back", and one-tap buttons
--   cover, coverBack, redirect               the screen covers the others (Settings over the hub); see Skin.wrap
--   zinc                  names of the stock toggle bindings and the no-op action of the touch blocker
--   when(init) -> bool                       false keeps this instance on its stock layout
--   model(session, instance, init)           the skin's own data and handlers on top of the stock VM's
--
-- Shared state lives in the global PRISM_SKIN (the engine's module cache is weak, this file may be reloaded):
--   sessions     id -> Session            seq          counter for session ids and request tokens
--   ready, off   native is usable / the reason it is not (nil while usable)
--   offScreens   spec id -> reason libpv refused that scene
--   svc, getenv  the F16Service link      maxCmd       longest command the bridge carries
--   readyCount   spec id -> how many times the screen came on natively
--   perf         frame timing counters    cover, guest*, pendingNav, ...   the cover / guest bookkeeping

local Skin = { VERSION = "4.0.0" }
PRISM_SKIN = PRISM_SKIN or { sessions = {}, seq = 0, off = nil, offScreens = {}, ready = false }
local G = PRISM_SKIN
Skin.G = G
-- The loaded module, for stock VMs the installer patches in place (their patched Lua finds the module here).
G.module = Skin

-- "auto": use Prism Native when libpv has it. "off": never (every skinned screen shows its stock layout).
Skin.mode = Skin.mode or "auto"
-- A finger that lands on a native control belongs to Prism Native until it lifts: the game's own (hidden) screen under
-- it is not given the touch. Set false to hand every touch to the game as well.
Skin.swallowTouches = Skin.swallowTouches ~= false
-- Navigation events that open a stock "guest" screen OVER the native ones, mapped to the frames to wait between hiding
-- the native screens and firing the event: libpv gives its GPU memory back first, so the stock screen loads with all of
-- it. Empty: Settings is a native screen (a modal layer over the hub), not a guest.
Skin.guestEvents = Skin.guestEvents or {}
-- Navigation events that open a native overlay over the screen that fires them: that screen stays (no depart slide).
Skin.overlayEvents = Skin.overlayEvents or { evt_to_settings_customize = true }

local unpack = unpack or table.unpack

-- F16Service (libpv adds Cmd/Out to it) carries every command and reply: Cmd("pc3d:...") sends, Cmd("env:KEY") + Out()
-- reads a reply (a leading \1 = not set), the per-frame event poll included.

--- Returns the F16Service object once it carries Cmd and Out, else nil. `api` is the engine's service lookup.
local function f16svc(api)
  local f = rawget(_G, "F16_SVC")
  -- the engine's api is a callable object, not always a Lua function (R98: never test its type, pcall it)
  if f == nil and api ~= nil then local ok, s = pcall(api, "F16Service"); if ok and s then f = s; rawset(_G, "F16_SVC", s) end end
  -- the probe runs under pcall: it never throws
  if f and pcall(function() return f.Cmd ~= nil and f.Out ~= nil end) and f.Cmd ~= nil and f.Out ~= nil then return f end
  return nil
end
--- Wraps F16Service as { cmd(c), getenv(key) }; getenv reads a reply variable through Cmd/Out.
local function f16link(f)
  local link = { cmd = function(c) return f.Cmd(c) end }
  function link.getenv(key)
    f.Cmd("env:" .. key)
    local v = f.Out()
    if type(v) ~= "string" or v:sub(1, 1) == "\1" then return nil end
    return v
  end
  return link
end
--- Prints "[PrismSkin] <args joined by spaces>" and mirrors the line into libpv's log once F16Service is known.
local function log(...)
  local parts = {}
  for i = 1, select("#", ...) do parts[#parts + 1] = tostring((select(i, ...))) end
  local msg = table.concat(parts, " ")
  print("[PrismSkin] " .. msg)
  -- libpv writes it to preview.log (/sdcard/Documents/FIFA16Preview)
  if G.svc then pcall(G.svc.cmd, "pc3d:ui:log:" .. (msg:gsub("%c", " ")):sub(1, 180)) end
end
Skin.log = log
pcall(rawset, _G, "PRISM_LOG", log)   -- R96: for skin models (the Settings model says which rows it left out)
local function traceback(err) if debug and debug.traceback then return debug.traceback(tostring(err), 2) end return tostring(err) end
--- Calls fn(...) under xpcall and logs the traceback on an error ("error in <where>"). Returns false when fn is not a
--- function or failed, else true plus up to three of fn's results.
local function safe(where, fn, ...)
  if type(fn) ~= "function" then return false end
  local args, n = { ... }, select("#", ...)
  local ok, a, b, c = xpcall(function() return fn(unpack(args, 1, n)) end, traceback)
  if not ok then log("error in " .. where .. ": " .. tostring(a)) return false end
  return true, a, b, c
end
local clock = (os and os.clock) or function() return 0 end
-- Real time in whole seconds. libpv's timeouts are real time; os.clock is process cpu time (every thread), which runs at
-- its own pace while the engine works or waits.
local wall = (os and os.time) or function() return 0 end

------------------------------------------------------------------------ expressions (Prism expression AST)
-- [prism-expr:begin] (copied by skinstall into lua/prism/jobs/prismexpr.lua: Prism Workers evaluate the same way)
-- This block is the single source of the expression evaluator and the value encoding: tools/prismexpr.js copies it into
-- lua/prism/jobs/prismexpr.lua (for the workers), minus the lines that start with `Skin.`.
--
-- Expression AST (tools/skinc.js compiles every "{...}" binding of a skin into one of these):
--   { lit = v }  { path = {"a", "b"} }  { ["not"] = e }  { neg = e }  { op = "+"|"-"|"*"|"/"|"%", a = e, b = e }
--   { cmp = "=="|"!="|">"|"<"|">="|"<=", a = e, b = e }  { ["and"] = {e, e} }  { ["or"] = {e, e} }
--   { tern = {cond, then, else} }
--   { tpl = {string | e, ...} }  { pipe = { {name, args}, ... }, v = e }
-- "+" concatenates when an operand is a string; other arithmetic on non-numbers, and division by zero, give nil.
-- Ordering comparisons only hold between two numbers or two strings. The pipes are listed in PIPES (tools/skinc.js).
local function truthy(v) return not (v == nil or v == false) end
local function fmtNum(n)
  if n == math.floor(n) and math.abs(n) < 1e15 then return string.format("%d", n) end
  return tostring(math.floor(n * 1e10 + 0.5) / 1e10)
end
local function str(v)
  local t = type(v)
  if v == nil then return "" end
  if t == "number" then return fmtNum(v) end
  if t == "boolean" then return v and "true" or "false" end
  if t == "table" then return "" end
  return tostring(v)
end
local function num(v)
  if type(v) == "number" then return v end
  if type(v) == "string" and v:match("%S") then return tonumber((v:gsub("[^%d%.%-]", ""))) or 0 end
  return 0
end
local function luaRound(x) return math.floor(x + 0.5) end
local function compactNum(v)
  local a = math.abs(v)
  if a >= 1e9 then return string.format("%.1f", v / 1e9) .. "B" end
  if a >= 1e6 then return string.format("%.1f", v / 1e6) .. "M" end
  if a >= 1e3 then return string.format("%.1f", v / 1e3) .. "K" end
  return string.format("%d", luaRound(v))
end
local function getPath(scope, p)
  local v = scope
  for k = 1, #p do
    if type(v) ~= "table" then return nil end
    v = v[p[k]]
  end
  return v
end
local EXPR_KEYS = { "path", "not", "neg", "op", "cmp", "and", "or", "tern", "tpl", "pipe" }
local function isLiteral(e) for i = 1, #EXPR_KEYS do if e[EXPR_KEYS[i]] ~= nil then return false end end return true end
local evalExpr
--- Evaluates expression `e` against the scope table `s` (binding name -> value). Never throws on bad data: nil results.
evalExpr = function(e, s)
  if e == nil then return nil end
  if type(e) ~= "table" then return e end
  if isLiteral(e) then return e.lit end
  if e.path then return getPath(s, e.path) end
  if e["not"] then return not truthy(evalExpr(e["not"], s)) end
  if e.neg then local v = evalExpr(e.neg, s); if type(v) == "number" then return -v end return nil end
  if e.op then
    local x, y = evalExpr(e.a, s), evalExpr(e.b, s)
    if e.op == "+" and (type(x) == "string" or type(y) == "string") then return str(x) .. str(y) end
    if type(x) ~= "number" or type(y) ~= "number" then return nil end
    local o = e.op
    if o == "+" then return x + y elseif o == "-" then return x - y elseif o == "*" then return x * y
    elseif o == "/" then if y == 0 then return nil end return x / y
    else if y == 0 then return nil end return x - math.floor(x / y) * y end
  end
  if e.cmp then
    local a, b = evalExpr(e.a, s), evalExpr(e.b, s)
    if e.cmp == "==" then return a == b end
    if e.cmp == "!=" then return a ~= b end
    local ta, tb = type(a), type(b)
    if not ((ta == "number" and tb == "number") or (ta == "string" and tb == "string")) then return false end
    if e.cmp == ">" then return a > b elseif e.cmp == "<" then return a < b elseif e.cmp == ">=" then return a >= b else return a <= b end
  end
  if e["and"] then local l = evalExpr(e["and"][1], s); if truthy(l) then return evalExpr(e["and"][2], s) end return l end
  if e["or"] then local r = evalExpr(e["or"][1], s); if truthy(r) then return r end return evalExpr(e["or"][2], s) end
  if e.tern then if truthy(evalExpr(e.tern[1], s)) then return evalExpr(e.tern[2], s) end return evalExpr(e.tern[3], s) end
  if e.tpl then
    local out = {}
    for i = 1, #e.tpl do local p = e.tpl[i]; out[i] = type(p) == "string" and p or str(evalExpr(p, s)) end
    return table.concat(out)
  end
  if e.pipe then
    local v = evalExpr(e.v, s)
    for i = 1, #e.pipe do
      local p = e.pipe[i]
      local name, A = p.name, p.args or { p.arg }
      if name == "upper" then v = string.upper(str(v))
      elseif name == "lower" then v = string.lower(str(v))
      elseif name == "int" then local x = num(v); v = x < 0 and math.ceil(x) or math.floor(x)
      elseif name == "fixed1" then v = string.format("%.1f", num(v))
      elseif name == "fixed2" then v = string.format("%.2f", num(v))
      elseif name == "pct" then v = string.format("%d", luaRound(num(v) * 100)) .. "%"
      elseif name == "sign" then if type(v) == "number" and v > 0 then v = "+" .. fmtNum(v) else v = str(v) end
      elseif name == "len" then if type(v) == "table" or type(v) == "string" then v = #v else v = 0 end
      elseif name == "default" then if v == nil or v == "" then v = A[1] end
      elseif name == "not" then v = not truthy(v)
      elseif name == "round" then v = luaRound(num(v))
      elseif name == "floor" then v = math.floor(num(v))
      elseif name == "ceil" then v = math.ceil(num(v))
      elseif name == "abs" then v = math.abs(num(v))
      elseif name == "clamp" then v = math.min(A[2], math.max(A[1], num(v)))
      elseif name == "money" then v = (A[1] == nil and "$" or A[1]) .. compactNum(num(v))
      elseif name == "compact" then v = compactNum(num(v))
      elseif name == "pad2" then local n2 = math.floor(num(v)); v = ((n2 >= 0 and n2 < 10) and "0" or "") .. string.format("%d", n2)
      elseif name == "asset" then if type(v) == "number" then v = { name = A[1], id = v } else v = {} end
      elseif name == "frame" then local f = num(v); if f < 0 then f = 0 elseif f > 1 then f = 1 end; v = luaRound(f * A[1])
      elseif name == "num" then v = num(v)
      elseif name == "ratio" then local d = num(A[1]); v = d ~= 0 and math.max(0, math.min(1, num(v) / d)) or 0
      elseif name == "trim" then v = (str(v):gsub("^%s+", ""):gsub("%s+$", ""))
      elseif name == "first" then if type(v) == "table" then v = v[1] end
      elseif name == "field" then if type(v) == "table" then v = v[A[1]] else v = nil end
      elseif name == "img" then if type(v) == "number" then v = { name = A[1], id = v } elseif type(v) == "string" and v ~= "" then v = { name = v, id = 0 } elseif type(v) ~= "table" then v = {} end
      elseif name == "nonempty" then if type(v) == "table" then v = next(v) ~= nil else v = v ~= nil and v ~= "" and v ~= false end
      elseif name == "map" then
        local key, out, def = string.lower(str(v)), nil, ""
        for k, val in string.gmatch(str(A[1]) .. ";", "([^=;]*)=([^;]*);") do
          if k == "*" then def = val elseif string.lower(k) == key then out = val end
        end
        v = out or def
      end
    end
    return v
  end
  return nil
end
Skin.eval = evalExpr

------------------------------------------------------------------------ native channel
-- Where enc finds the translator: set below this block in PrismSkin.lua (R98d, `translator`); nil on the workers, which
-- read PRISM_I18N directly.
local trHook = nil

--- Encodes a value for a native command: "x" nil, "b1" / "b0" boolean, "n<number>", "i<family>#<id>" for an image
--- reference { name = "$Family", id = n }, "s<text>" for a string.
local function enc(v)
  local t = type(v)
  if v == nil then return "x" end
  if t == "boolean" then return v and "b1" or "b0" end
  if t == "number" then if v ~= v then return "n0" end return "n" .. tostring(v) end
  if t == "table" then
    if v.name ~= nil then return "i" .. tostring(v.name) .. "#" .. tostring(v.id or 0) end
    return "x"
  end
  -- A translated variant (src/variants/pt-BR) registers PRISM_I18N: every string that reaches the screen goes through its
  -- tr(), so the raw values the screens compare and branch on stay as the game made them.
  local s = tostring(v)
  local i18n
  if trHook then i18n = trHook() else i18n = rawget(_G, "PRISM_I18N") end
  if i18n then s = i18n.tr(s) end
  -- Only the record separators (NUL and \29 \30 \31) are reserved and become spaces; "|" is safe inside values because
  -- commands split on their first fields only.
  return "s" .. string.gsub(s, "[%z\29\30\31]", " ")
end
Skin.enc = enc
-- [prism-expr:end]

-- pt-BR: the translator's whole source (its tables and code: PrismI18nData.lua), written here by the variant's post.js;
-- nil in the other builds.
local I18N_EMBED = nil

--- The translator enc uses: PRISM_I18N when it knows its tables. Otherwise (R98d: on the phone the variant's modules did
--- not leave a working one, so every dynamic text stayed English) this file loads its own copy, once per game run, and
--- says in the log which one the screens use.
local function translator()
  local t = rawget(_G, "PRISM_I18N")
  if t ~= nil and t == G.i18nOk then return t end
  if t == nil and I18N_EMBED == nil then return nil end
  local function works(x) return type(x) == "table" and type(x.tr) == "function" and (type(x.size) ~= "function" or x.size() > 0) end
  if works(t) then
    G.i18nOk = t
    if not G.i18nSaid then G.i18nSaid = true; log("i18n: the variant's translator (" .. tostring(t.size and t.size() or "?") .. " entries)") end
    return t
  end
  if I18N_EMBED ~= nil and not G.i18nTried then
    G.i18nTried = true
    local why = t == nil and "no PRISM_I18N" or "PRISM_I18N without its tables"
    local ls, err = rawget(_G, "loadstring"), nil
    local f
    if ls then f, err = ls(I18N_EMBED, "=PrismI18nData (PrismSkin copy)") else err = "no loadstring" end
    if f then local ok, e = pcall(f); if not ok then err = e end end
    t = rawget(_G, "PRISM_I18N")
    if works(t) then
      G.i18nOk = t
      log("i18n: " .. why .. " from the variant's modules; PrismSkin's own copy loaded (" .. tostring(t.size()) .. " entries)")
      return t
    end
    log("i18n: " .. why .. "; PrismSkin's own copy failed: " .. tostring(err))
  end
  return t
end
trHook = translator

--- A request token that is unique per game run (a salt plus G.seq); libpv echoes it in its replies so a late reply can
--- be told from an old one.
local function token()
  if not G.salt then
    G.salt = (tostring({}):match("0x(%x+)") or tostring({}):match("(%x+)$") or "0") ..
      string.format("%x", math.floor(((os and os.time and os.time()) or 0) % 1048576))
  end
  G.seq = G.seq + 1
  return G.salt .. "s" .. tostring(G.seq)
end

--- Sends one native command through the bridge. A command longer than G.maxCmd (what the bridge was measured to carry)
--- goes out as "pc3d:ui:+<id>:<part>" chunks closed by "=<id>:<part>". Returns false without a bridge or on a failure.
local function send(cmd)
  local svc = G.svc
  if not svc then return false end
  if G.perf then G.perf.cmds = G.perf.cmds + 1 end
  local max = G.maxCmd or 200
  if #cmd <= max then return pcall(svc.cmd, cmd) end
  G.chunkId = ((G.chunkId or 0) + 1) % 36
  local cid = string.sub("0123456789abcdefghijklmnopqrstuvwxyz", G.chunkId + 1, G.chunkId + 1)
  local body = cmd:match("^pc3d:ui:(.*)$") or cmd
  local room = max - 12
  local i, n = 1, #body
  while i <= n do
    local part = body:sub(i, i + room - 1)
    i = i + room
    local last = i > n
    local ok = pcall(svc.cmd, "pc3d:ui:" .. (last and "=" or "+") .. cid .. ":" .. part)
    if not ok then return false end
  end
  return true
end
Skin.send = send

--- Handshake with libpv, once per game run (a reply that lands late is picked up by the next screen's call). Sets
--- G.svc, G.getenv, G.maxCmd and G.ready, or G.off (the reason) when Prism Native is not usable. Needs Prism Native 4.x
--- with a working GPU and touch input. After 4 unanswered tries (one per opening screen) it gives up: stock layouts
--- everywhere. `api` is the engine's service lookup (init.api). Returns true when native is ready.
local function hello(api)
  if G.ready then return true end
  if G.off then return false end
  if Skin.mode == "off" then G.off = "Prism Native switched off in PrismSkin.lua"; return false end
  local f = f16svc(api)
  if not f then
    -- R98: not for good on the first miss (the main menu asks at boot, before any screen has looked the service up)
    G.svcTries = (G.svcTries or 0) + 1
    if G.svcTries >= 4 then G.off = "no F16Service.Cmd (this APK's libpv is too old)"; log("native: " .. G.off) end
    return false
  end
  local svc = f16link(f)
  G.svc = svc
  local getenv = svc.getenv
  G.getenv = getenv
  -- an earlier hello may have been answered since (a reply can land after the command returns)
  local tok, h = G.helloTok or token(), nil
  if G.helloTok then
    h = getenv("PRISM_UI")
    if not (type(h) == "string" and h:find("tok=" .. tok, 1, true)) then h = nil end
  end
  if not h then
    pcall(svc.cmd, "pc3d:ui:hello:" .. tok)
    h = getenv("PRISM_UI")
  end
  log("native: hello " .. tok .. " -> " .. tostring(h))
  if type(h) ~= "string" or h:sub(1, 2) ~= "ok" or not h:find("tok=" .. tok, 1, true) then
    G.helloTries = (G.helloTries or 0) + 1
    if G.helloTries >= 4 then
      G.off = "libpv without Prism Native"; log("native: no reply to hello on " .. G.helloTries .. " screens - career screens use their stock layouts"); return false
    end
    G.helloTok = tok
    log("native: no hello reply yet (try " .. G.helloTries .. "), this screen stays on its stock layout")
    return false
  end
  G.helloTok = nil
  if Skin.swallowTouches == false then pcall(svc.cmd, "pc3d:ui:swallow:0") end
  local v = h:match("v=([%d%.]+)")
  if not v or tonumber(v:match("^(%d+)")) < 4 then G.off = "libpv has Prism Native " .. tostring(v) .. " (4.x needed)"; log("native: " .. G.off); return false end
  if h:find(";gl=-1", 1, true) or h:find(";touch=-1", 1, true) then G.off = "native reported " .. h; log("native: unavailable (" .. h .. ")"); return false end
  -- "waitpolls" (R98e libpv): a layer waiting for its ready is dropped only once this thread had its frames, or after
  -- 30 s; an older libpv drops it 3 s after its open whatever this thread did (see Session:goLive)
  G.waitLimit = h:find("waitpolls", 1, true) and 30 or 3
  -- How long may one command be? Some bridges copy into fixed buffers: probe with growing payloads (240, 960, 3800
  -- bytes) and keep the largest size that came back intact (the limit is that size + 30 for the command head).
  G.maxCmd = 200
  for _, n in ipairs({ 240, 960, 3800 }) do
    local t2 = token()
    local payload = string.rep("x", n)
    pcall(svc.cmd, "pc3d:ui:probe:" .. t2 .. ":" .. n .. ":" .. payload)
    local r = getenv("PRISM_UI_PROBE")
    local rt, got
    if type(r) == "string" then rt, got = r:match("^([^:]+):(%d+)$") end
    if rt == t2 and tonumber(got) == n then G.maxCmd = n + 30 else break end
  end
  G.ready = true
  log("native: Prism Native " .. v .. " ready (commands up to " .. G.maxCmd .. " bytes)")
  return true
end

--- Sends the theme tokens (the user-editable palette in PrismTheme.lua) to libpv, once per theme table.
local function sendTheme(theme)
  if type(theme) ~= "table" or G.themeSent == theme then return end
  local parts = {}
  for k, v in pairs(theme) do if type(v) == "string" then parts[#parts + 1] = k .. "=" .. v end end
  table.sort(parts)
  if #parts > 0 then send("pc3d:ui:theme:" .. table.concat(parts, ";")) end
  G.themeSent = theme
end
--- Can a native screen come up now? True once the first hello succeeded and `skinId` (optional) has not been refused by
--- libpv. Lua that opens a screen with no stock fallback (the pause menu's Player Performance) asks first.
function Skin.available(skinId)
  if not G.ready or G.off then return false end
  if skinId and G.offScreens[skinId] then return false end
  return true
end
--- Plays a named timeline of a skin (spec.motion = { name = timeline }) on a named node ("*" = the whole screen) of the
--- live session of skin `skinId`, e.g. PrismSkin.play("MatchSelect", "advance", "pulse"). Returns true when sent.
function Skin.play(skinId, node, timeline)
  if not G.ready then return false end
  for id, s in pairs(G.sessions) do
    if not s.dead and s.spec.id == skinId then send("pc3d:ui:play:" .. id .. "|" .. tostring(node or "*") .. "|" .. tostring(timeline)); return true end
  end
  return false
end
--- Re-themes every native screen live from any Lua (e.g. club colours): PrismSkin.setTheme({ accent = "#C8102E" }).
function Skin.setTheme(tokens)
  if not G.ready then return end
  local parts = {}
  for k, v in pairs(tokens) do parts[#parts + 1] = k .. "=" .. tostring(v) end
  table.sort(parts)
  if #parts > 0 then send("pc3d:ui:theme:" .. table.concat(parts, ";")) end
end

------------------------------------------------------------------------ league palettes
-- PrismTheme.lua carries the base palette (purple) plus `palettes` (each only the tokens it changes) and `leagues`
-- (league id -> palette name, `default` for the rest) and `outside` (the palette outside a career). libpv keeps every token Lua
-- sets, so switching palettes sends the new palette's tokens and, for the tokens it leaves alone, the base values back.

--- The career's sessionVars (the module registers itself as PRISM_SESSION_VARS, see src/patches/Theme.patch.js).
local function careerVars() return rawget(_G, "PRISM_SESSION_VARS") or rawget(_G, "CAREER_SESSION_VARS") end

--- The palette name for league `id` ("base" outside the LUT's knowledge).
function Skin.paletteFor(theme, id)
  theme = theme or G.theme
  local map = type(theme) == "table" and theme.leagues
  if type(map) ~= "table" then return "base" end
  return map[tonumber(id) or -1] or map.default or "base"
end

--- Is a career (manager or player) the game mode being played?
function Skin.inCareer()
  local sv = careerVars()
  if not (sv and sv.get) then return false end
  local ok, v = pcall(sv.get, "InCareerMode")
  return ok and v and true or false
end

--- The palette outside a career (PrismTheme.outside: FC27's green).
function Skin.outsidePalette(theme)
  theme = theme or G.theme
  return type(theme) == "table" and type(theme.outside) == "string" and theme.outside or "base"
end

--- Is League Mode or Tournament Mode the game mode being played?
function Skin.inLeagueOrTourney()
  local sv = careerVars()
  if not (sv and sv.get) then return false end
  local okL, l = pcall(sv.get, "InLeagueMode")
  local okT, tm = pcall(sv.get, "InTourneyMode")
  return (okL and l and true) or (okT and tm and true) or false
end

--- The palette PrismTheme's `leagues` names for competition `id` itself (no `default`), else nil.
local function namedPalette(theme, id)
  theme = theme or G.theme
  local map = type(theme) == "table" and theme.leagues
  return type(map) == "table" and map[tonumber(id) or -1] or nil
end

--- The palette the user's situation calls for: the user's league in a career; in League and Tournament modes the
--- competition's own palette when PrismTheme has one (R98: the Premier League purple, the Champions League navy, ...),
--- else, like everywhere else, the outside one (FC27's green).
function Skin.userPalette(theme)
  local sv = careerVars()
  local ok, id = false, nil
  if sv and sv.get then ok, id = pcall(sv.get, "currentUserLeagueID") end
  if Skin.inCareer() then return Skin.paletteFor(theme, ok and id or nil) end
  if Skin.inLeagueOrTourney() then return namedPalette(theme, ok and id or nil) or Skin.outsidePalette(theme) end
  return Skin.outsidePalette(theme)
end

--- Shows palette `name` ("base" = PrismTheme's own tokens) on every native screen; nothing is sent when it is up already.
function Skin.usePalette(name, theme)
  theme = theme or G.theme
  if type(theme) ~= "table" then return false end
  local pals = type(theme.palettes) == "table" and theme.palettes or {}
  local pal = pals[name]
  if name ~= "base" and type(pal) ~= "table" then name, pal = "base", nil end
  if G.palette == name or not G.ready then return G.palette == name end
  local tokens = {}
  for k, v in pairs(G.paletteKeys or {}) do if type(theme[k]) == "string" then tokens[k] = theme[k] end end
  G.paletteKeys = {}
  for k, v in pairs(pal or {}) do if type(v) == "string" then tokens[k] = v; G.paletteKeys[k] = true end end
  Skin.setTheme(tokens)
  G.palette = name
  log("theme: palette " .. tostring(name))
  return true
end

--- A screen showing another competition (Standings, Player Stats) switches to that one's palette; nil goes back to
--- the user's palette. A career is coloured by competition; League and Tournament modes by a competition PrismTheme has a
--- palette for (R98); elsewhere the screens keep FC27's green, unless `force` (the career's team picker, which opens
--- before the game mode is set).
function Skin.competitionPalette(id, force)
  if id == nil then return Skin.usePalette(Skin.userPalette()) end
  if not (force or Skin.inCareer()) then
    if Skin.inLeagueOrTourney() then return Skin.usePalette(namedPalette(nil, id) or Skin.outsidePalette()) end
    return Skin.usePalette(Skin.outsidePalette())
  end
  return Skin.usePalette(Skin.paletteFor(nil, id))
end

--- spec.followPalette (the career hub): the screen on top keeps the palette of the user's competition live. The hub
--- changes the competition while the date advances (the next match is a Champions League one: navy; back to the
--- league: its colour) and, until R98, the palette only followed when the screen opened again. Checked every 10 polls,
--- only while the screen is the newest live one (a Standings over it shows its own competition) and no stock screen
--- has the native ones hidden.
local function followPalette()
  G.palPoll = ((G.palPoll or 0) + 1) % 10
  if G.palPoll ~= 0 or G.guestHidden then return end
  local top
  for _, s in pairs(G.sessions) do if not s.dead and (not top or (s.seqNo or 0) > (top.seqNo or 0)) then top = s end end
  if top and top.spec.followPalette and not top.leaving then Skin.usePalette(Skin.userPalette()) end
end

------------------------------------------------------------------------ poll (one per frame for all screens)
-- With no native session left the shell (the room behind the screens) must go too, or it would cover the stock screens.
local function closeShellIfIdle()
  for _, s in pairs(G.sessions) do if not s.dead then return end end
  if G.shellOpen then send("pc3d:ui:close:shell"); G.shellOpen = false end
end
Skin.closeShellIfIdle = closeShellIfIdle

--- The per-frame poll, run by every live session's update (the reply is identical within a frame, so a repeat is
--- skipped): settles pending open replies, reads libpv's state ("PRISM_UI_EV": touch / GPU flags, a sequence number and
--- the queued events), drops every screen to its stock layout when libpv stops answering or reports a failure, runs the
--- models' ticks and hands each queued event to its session.
local function pollAll()
  local live = 0
  for _, s in pairs(G.sessions) do if not s.dead then live = live + 1 end end
  if live == 0 then closeShellIfIdle(); return end
  -- An open whose reply had not landed yet is settled now; waiting is counted in frames, not clock time (os.clock is
  -- process cpu time).
  for _, s in pairs(G.sessions) do
    if s.openTok and not s.dead then
      local r = G.getenv("PRISM_UI_LOAD")
      if type(r) == "string" and r:sub(-#s.openTok - 1) == ":" .. s.openTok then
        s.openTok = nil
        if r:sub(1, 3) ~= "ok:" then
          local why = r:match("^err:(.*):[^:]*$") or r
          log("native: " .. tostring(s.spec.id) .. " did not open (" .. tostring(why) .. ")")
          G.offScreens[s.spec.id] = why
          s:fallback(why)
        end
      else
        s.openFrames = (s.openFrames or 0) + 1
        if s.openFrames > 120 then s.openTok = nil; log("native: " .. tostring(s.spec.id) .. ": no reply to open after 120 frames"); s:fallback("no reply to open") end
      end
    end
  end
  -- The poll: Cmd("env:PRISM_UI_EV") + Out() is answered by libpv directly. Reply: "s<any><touch><gl>:<seq>" followed
  -- by the queued events, each introduced by \30 as "<kind>:<layer>:<rest>".
  local r = G.getenv("PRISM_UI_EV")
  local P = G.perf
  if P then P.reads = (P.reads or 0) + 1 end
  local head = type(r) == "string" and r:match("^([^\30]*)") or ""
  local any, touch, gl, rtok = head:match("^s(.)(.)(.):(.*)$")
  local reason
  if not rtok then
    -- Nothing that looks like libpv behind F16Service: a few frames of grace, then the stock layouts.
    G.noReply = (G.noReply or 0) + 1
    if G.noReply > 120 then reason = "no reply from libpv for 120 frames (last: " .. tostring(r):sub(1, 40) .. ")" else return end
  else
    G.noReply = 0
    if P then local n = tonumber(rtok:match("%d+")) or 0; P.seqLo = P.seqLo or n; P.seqHi = n end
  end
  if not reason and touch == "x" then reason = "touch input unavailable"
  elseif not reason and gl == "x" then reason = "GPU rejected the Prism shaders" end
  if not reason and (touch ~= "1" or gl ~= "1") and not G.guestHidden then
    -- While a stock screen has the native ones hidden, libpv has freed its GPU memory on purpose and an older libpv
    -- reports gl 0 until it draws again: that is not a GPU that fails, so the count is skipped while a guest is up.
    G.notReady = (G.notReady or 0) + 1
    if G.notReady > 300 then reason = "not ready after 300 frames (touch " .. tostring(touch) .. ", gl " .. tostring(gl) .. ")" end
  else G.notReady = 0 end
  if reason then
    log("native: back to the stock layouts: " .. reason)
    G.off = reason
    for _, s in pairs(G.sessions) do s:fallback(reason) end
    closeShellIfIdle()
    return
  end
  -- "s0": libpv has no layer open. Under live screens (open settled, not on their way out) that means it dropped them
  -- (see Session:goLive): three polls in a row, then they open again - the ones already shown at once, the others when
  -- their ready goes.
  local lost = false
  if any == "0" then for _, s in pairs(G.sessions) do if not s.dead and not s.leaving and not s.openTok then lost = true break end end end
  G.lostPolls = lost and (G.lostPolls or 0) + 1 or 0
  if G.lostPolls >= 3 then
    G.lostPolls = 0
    for _, s in pairs(G.sessions) do
      if not s.dead and not s.leaving and not s.openTok then
        if s.live then if s:reopen("libpv has no screen open") then s:goLive() end else s.lost = true end
      end
    end
  end
  -- Per-frame work of skin models (s.onTick; a screen whose stock VM has no update of its own, Settings, still gets
  -- it). It runs before the repeat check below because libpv's reply stays the same while nothing happens. Every live
  -- screen polls, so with two screens up a tick comes twice a frame: tick counts are "at least" frames.
  for _, s in pairs(G.sessions) do if not s.dead and s.onTick then safe(tostring(s.spec.id) .. " tick", s.onTick, s) end end
  safe("follow palette", followPalette)
  -- The same reply twice (several sessions in one frame, or a repeated read): its events were already taken.
  if rtok == G.lastRtok then return end
  G.lastRtok = rtok
  for ev in string.gmatch(r, "\30([^\30]+)") do
    local kind, layer, rest = ev:match("^(%a+):([^:]+):(.*)$")
    local s = layer and G.sessions[layer]
    if s and not s.dead then
      G.inTap = kind == "tap" and s or nil
      s:event(kind, rest)
      G.inTap = nil
    end
  end
end

------------------------------------------------------------------------ session (one per skinned screen instance)
-- A Session is the live link between one screen instance and its native scene. Its state:
--   env, seen          every value the screen published (raw) by stock binding name; bindings published at least once
--   dirty              stock bindings changed since the last flush
--   last               the last encoded value sent per native name (a repeat is not sent again)
--   handlers, dataHandlers, dataHandlersBy   the actions the screen registered (plain, and data actions per binding)
--   depsOf, listsOf    stock binding -> derived values / native lists that read it
--   providers          stock Subscribe callbacks of the bindings the skin reads (see runProviders)
--   dead, leaving, departed, busy, gone   lifecycle flags (see Session:event, setBusy, setGone, fallback, stop)
--   openWall, live, lost, reopens          when its layer was opened (os.time), its ready went, libpv lost it, how
--                                          many times it was opened again (see Session:goLive, reopen)
local Session = {}
Session.__index = Session

--- Creates the session of one screen instance: indexes the spec's derived values and lists by the bindings they read.
local function newSession(spec, init)
  local s = setmetatable({}, Session)
  s.spec, s.init = spec, init
  G.seq = G.seq + 1
  s.id = (spec.id or "skin") .. "#" .. tostring(G.seq)
  s.seqNo = G.seq          -- opening order (the newest live session is the screen on top)
  s.env = {}               -- every value the screen published (raw), by binding name
  s.seen = {}              -- bindings published at least once (a repeat of the same scalar is skipped)
  s.handlers, s.dataHandlers, s.dataHandlersBy = {}, {}, {}
  s.out, s.outN = {}, 0    -- native values waiting to be sent this frame
  s.last = {}              -- last value sent per native binding (string encoded)
  s.dirty = {}             -- original binding names changed since the last flush
  s.listDirty = {}
  s.depsOf = {}            -- original binding -> list of derived value specs
  for _, v in ipairs(spec.values or {}) do for _, d in ipairs(v.deps or {}) do s.depsOf[d] = s.depsOf[d] or {}; table.insert(s.depsOf[d], v) end end
  s.listsOf = {}
  for _, L in ipairs(spec.lists or {}) do
    local seen = {}
    if L.from then s.listsOf[L.from] = s.listsOf[L.from] or {}; table.insert(s.listsOf[L.from], L); seen[L.from] = true end
    for _, d in ipairs(L.deps or {}) do if not seen[d] then seen[d] = true; s.listsOf[d] = s.listsOf[d] or {}; table.insert(s.listsOf[d], L) end end
  end
  -- Every stock binding the skin reads. Stock VMs often publish lazily (im.Subscribe providers that run when a view
  -- subscribes); the hidden Zinc layout subscribes what IT shows, so the shim runs those of the skin.
  s.needs = {}
  for b in pairs(spec.pass or {}) do s.needs[b] = true end
  for d in pairs(s.depsOf) do s.needs[d] = true end
  for d in pairs(s.listsOf) do s.needs[d] = true end
  s.providers = {}
  return s
end

--- Sends the open of the session's layer (`flags` "wait" or "wait,back"), after the shell's when the screen has one (a
--- shell still up is kept). Returns libpv's reply and this open's token (the reply is an older one while this open's
--- has not landed).
function Session:sendOpen(flags)
  local spec = self.spec
  if spec.shell then
    local t = token()
    send("pc3d:ui:open:shell|" .. spec.shell .. "|" .. t .. "|keep")
    local r = G.getenv("PRISM_UI_LOAD")
    G.shellOpen = r == nil or (type(r) == "string" and r:sub(1, 3) == "ok:")
    if not G.shellOpenLogged then G.shellOpenLogged = true; log("native: shell open -> " .. tostring(r)) end
  end
  local tok = token()
  send("pc3d:ui:open:" .. self.id .. "|" .. spec.scene .. "|" .. tok .. "|" .. flags)
  self.openWall = wall()   -- libpv drops the layer when its ready has not come 3 s after this (see Session:goLive)
  return G.getenv("PRISM_UI_LOAD"), tok
end

--- Opens the native scene (and the shared shell scene behind it, once) and registers the session. The reply may not
--- have landed yet: the open is then settled by pollAll on a later frame. Returns false when libpv refused the scene
--- (the screen then stays stock and the spec id is remembered in G.offScreens).
function Session:open()
  local spec = self.spec
  local flags = G.dirBack and "wait,back" or "wait"
  G.dirBack = nil
  local r, tok = self:sendOpen(flags)
  local mine = type(r) == "string" and r:sub(-#tok - 1) == ":" .. tok
  if mine and r:sub(1, 3) ~= "ok:" then
    local why = r:match("^err:(.*):[^:]*$") or r
    log("native: " .. tostring(spec.id) .. " stays on its stock layout (" .. tostring(why) .. ")")
    G.offScreens[spec.id] = why
    return false
  end
  if not mine then
    -- The reply has not landed yet (or is an older one): go on natively, a later frame settles it.
    self.openTok, self.openAt = tok, clock()
    log("native: " .. tostring(spec.id) .. " open reply pending (" .. tostring(r) .. ")")
  else
    log("native: " .. tostring(spec.id) .. " open -> " .. r)
  end
  G.sessions[self.id] = self
  return true
end

--- Returns a copy of the screen's `init` whose `im` (publish / subscribe / actions) and `nav` are watched by this
--- session: publishes are mirrored to the native layer, registered actions stay callable from native taps, and nav
--- events trigger the depart / busy bookkeeping.
function Session:wrapInit(init)
  local s = self
  local im = init.im
  local nav = init.nav or (type(init.data) == "table" and type(init.data.nav) == "table" and init.data.nav) or nil
  local ws = setmetatable({}, { __index = im })
  ws.Publish = function(binding, value, ...)
    local r = im.Publish(binding, value, ...)
    s:onPublish(binding, value)
    return r
  end
  ws.Subscribe = function(binding, fn, ...)
    local r = im.Subscribe(binding, fn, ...)
    if type(fn) == "function" and s.needs[binding] then s.providers[#s.providers + 1] = { binding, fn } end
    return r
  end
  ws.Refresh = function(binding, ...)
    local r = im.Refresh and im.Refresh(binding, ...)
    if binding ~= nil then s:onPublish(binding, s.env[binding], true) end
    return r
  end
  -- Wraps a stock action handler. While something sits on top of this screen its stock actions must not run, whatever
  -- reaches them (the phone's back key reaches the hub's act_exit, which would open the exit-career popup under
  -- Settings and leave the career with Settings still open). Instead:
  --   * a covering native screen (spec.cover, Settings over the hub) owns the stock actions: its own stock back
  --     (act_cancel = revert) is redirected through spec.redirect to its native Back; the covered screens' back / exit
  --     close it through spec.coverBack, and their other actions do nothing;
  --   * a stock guest screen (G.guestHidden): back / exit closes the guest, other actions do nothing.
  local function guarded(action, fn)
    if type(fn) ~= "function" then return fn end
    return function(...)
      local cv = G.cover
      if cv and not cv.dead and not cv.leaving then
        if cv == s then
          local to = s.spec.redirect and s.spec.redirect[action]
          if to and s.handlers[to] then log("stock action " .. tostring(action) .. " of " .. tostring(s.spec.id) .. " -> " .. tostring(to)); return s.handlers[to](to) end
        elseif s.underCover == cv then   -- (a screen that opens over it later, a popup, keeps its actions)
          local back = action == "act_exit" or action == "act_back" or action == "act_cancel" or (s.spec.backActions and s.spec.backActions[action])
          log("stock action " .. tostring(action) .. " of " .. tostring(s.spec.id) .. " under " .. tostring(cv.spec.id) .. ": " .. (back and "closes it" or "ignored"))
          local h = back and cv.spec.coverBack and cv.handlers[cv.spec.coverBack]
          if h then safe(tostring(cv.spec.id) .. " back", h, cv.spec.coverBack) end
          return
        end
      end
      if s.underGuest and G.guestHidden then
        local back = action == "act_exit" or action == "act_back" or (s.spec.backActions and s.spec.backActions[action])
        log("stock action " .. tostring(action) .. " of " .. tostring(s.spec.id) .. " under " .. tostring(G.guestWho or "a stock screen") .. ": " .. (back and "closes it instead" or "ignored"))
        if back then Skin.guestClose() end
        return
      end
      return fn(...)
    end
  end
  ws.RegisterAction = function(action, fn, ...)
    s.handlers[action] = fn
    return im.RegisterAction(action, guarded(action, fn), ...)
  end
  ws.RegisterDataAction = function(binding, action, fn, ...)
    s.dataHandlers[action] = { binding = binding, fn = fn }
    s.dataHandlersBy[tostring(binding) .. "|" .. tostring(action)] = s.dataHandlers[action]
    return im.RegisterDataAction(binding, action, guarded(action, fn), ...)
  end
  ws.UnregisterAction = function(action, ...)
    s.handlers[action] = nil; s.dataHandlers[action] = nil
    for k in pairs(s.dataHandlersBy) do if k:sub(-#tostring(action) - 1) == "|" .. tostring(action) then s.dataHandlersBy[k] = nil end end
    return im.UnregisterAction(action, ...)
  end
  ws.ChangeActionState = function(action, state, ...)
    local r = im.ChangeActionState and im.ChangeActionState(action, state, ...)
    s:onPublish("__state_" .. tostring(action), state)
    return r
  end
  s.im, s.wim = im, ws
  local back = s.spec.backEvents or { evt_back = true }
  local wn = setmetatable({}, { __index = nav })
  wn.Event = function(a, evt, ...)
    if back[evt] then G.dirBack = true; send("pc3d:ui:dir:back") end
    log("nav " .. tostring(s.spec.id) .. " -> " .. tostring(evt))
    local e = tostring(evt)
    local overlay = e:match("^evt_show") or e:match("^evt_hide") or Skin.guestEvents[e] or Skin.overlayEvents[e]
    -- Fired while the screen is still being built (the hub after a match opens the Match Results overlay from its
    -- constructor): the screen waits for that overlay and both come on in the same frame, instead of the hub first.
    if G.building == s and overlay then s.overlayGate = 0 end
    -- Fired by a native tap's handler: the screen answers now - its content slides out to the room while the game
    -- builds the next screen (it comes back if no screen change follows).
    if G.inTap == s and not overlay and not s.dead and not s.departed then
      s.departed = 0
      send("pc3d:ui:depart:" .. s.id .. "|" .. (back[evt] and "-" or "+"))
    end
    -- The tapped button hides until something answers it (see Session:setBusy); a screen whose own screen change was
    -- fired from a tap on another layer (an overlay's Advance, a popup's Yes) hides at once (see Session:setGone).
    if G.inTap == s and s.tapAct then s:setBusy(s.tapAct)
    elseif G.inTap and G.inTap ~= s and not overlay and not s.dead then s:setGone(true) end
    return nav.Event(a, evt, ...)
  end
  s.nav, s.wnav = nav, wn
  -- spec.back = "<action>": the phone's back key runs that action of the screen (the engine calls nav.Back on its own
  -- nav, not on the copy the screen holds); the previous Back comes back when the session stops
  if nav and s.spec.back then
    local prev = nav.Back
    s.restoreBack = function() if nav.Back == s.backFn then nav.Back = prev end end
    s.backFn = function()
      local h = s.handlers[s.spec.back]
      -- only while this screen is the one on top: a screen opened after it (Squad Hub over a hub the engine keeps) gets
      -- the engine's own back, which returns to the hub instead of leaving the career
      local above
      for _, x in pairs(G.sessions) do if x ~= s and not x.dead and (x.seqNo or 0) > (s.seqNo or 0) and (not above or x.seqNo > above.seqNo) then above = x end end
      log("back key on " .. tostring(s.spec.id) .. " -> " .. (above and ("the screen above it, " .. tostring(above.spec.id)) or tostring(s.spec.back)) .. (h and "" or " (no handler: engine default)"))
      if above then
        -- a covering screen (Settings) closes through its own Back
        local cb = above.spec.coverBack and above.handlers[above.spec.coverBack]
        if cb and not above.leaving then return cb(above.spec.coverBack) end
      elseif h and not s.dead and not s.leaving then return h(s.spec.back) end
      if prev then return prev() end
      return nav.Event(nil, "evt_back")
    end
    nav.Back = s.backFn
  end
  local copy = {}
  for k, v in pairs(init) do copy[k] = v end
  copy.im = ws
  if init.nav then copy.nav = wn end -- only replace a nav the screen was actually given
  return copy
end

--- Records a value the screen published (or re-published through Refresh); its binding is sent by the next flush.
function Session:onPublish(binding, value, force)
  if binding == nil or self.dead then return end
  if G.perf then G.perf.pub = G.perf.pub + 1 end
  -- The same scalar again (stock screens re-publish every update): nothing to do.
  if not force and type(value) ~= "table" and self.env[binding] == value and self.seen[binding] then return end
  self.seen[binding] = true
  self.env[binding] = value
  self.dirty[binding] = true
  self.anyDirty = true
end

local function queue(s, name, value)
  local e = enc(value)
  if s.last[name] == e then return end
  s.last[name] = e
  s.outN = s.outN + 1
  s.out[s.outN] = name .. "=" .. e
end

--- Sends what changed since the last flush: passed bindings, derived values (re-evaluated for the bindings they read)
--- and lists, as one batched "v" command per session. `force` resends everything.
function Session:flush(force)
  if self.dead then return end
  local spec, env = self.spec, self.env
  if force then for k in pairs(env) do self.dirty[k] = true end end
  if not self.anyDirty and not force then return end
  self.anyDirty = false
  local dirty = self.dirty
  self.dirty = {}
  local pass = spec.pass or {}
  local lists = {}
  if spec.shellPass and G.shellOpen then
    local sh = {}
    for b, to in pairs(spec.shellPass) do if dirty[b] then local e = enc(env[b]); if G["shell:" .. to] ~= e then G["shell:" .. to] = e; sh[#sh + 1] = to .. "=" .. e end end end
    if #sh > 0 then send("pc3d:ui:v:shell|" .. table.concat(sh, "\31")) end
  end
  for b in pairs(dirty) do
    local to = pass[b]
    if to then
      if type(to) == "table" then for _, t in ipairs(to) do queue(self, t, env[b]) end else queue(self, to, env[b]) end
    end
    local ds = self.depsOf[b]
    if ds then for _, v in ipairs(ds) do local ok, val = safe(spec.id .. " " .. v.name, evalExpr, v.expr, env); if ok then queue(self, v.name, val) end end end
    local ls = self.listsOf[b]
    if ls then for _, L in ipairs(ls) do lists[L] = true end end
  end
  if force then for _, v in ipairs(spec.values or {}) do if not v.deps or #v.deps == 0 then local ok, val = safe(spec.id .. " " .. v.name, evalExpr, v.expr, env); if ok then queue(self, v.name, val) end end end end
  if self.outN > 0 then
    if G.perf then G.perf.vals = G.perf.vals + self.outN end
    send("pc3d:ui:v:" .. self.id .. "|" .. table.concat(self.out, "\31", 1, self.outN))
    self.out, self.outN = {}, 0
  end
  if force then for _, L in ipairs(spec.lists or {}) do lists[L] = true end end
  for L in pairs(lists) do self:sendList(L) end
end

--- Sends the rows of native list `L` (and its selection) when they changed. Rows come from an array binding (fields
--- computed per item, optional filter / max) or from fixed slot bindings (one row per numbered slot, optional `when`).
--- Remembers which source item each native row stands for, so a tap maps back to it.
function Session:sendList(L)
  local rows, n, map = {}, 0, {}
  local scope = setmetatable({}, { __index = self.env })
  local sel
  local id = self.spec.id
  if L.rows then
    if self.selSlot then self.selSlot[L.list] = nil end
    for s = 1, #L.rows do
      local R = L.rows[s]
      local keep = true
      if R.when then local ok, v = safe(id .. " " .. L.list .. " when", evalExpr, R.when, scope); keep = ok and truthy(v) end
      if keep then
        local f = {}
        for k = 1, #R.fields do local ok, v = safe(id .. " " .. L.list, evalExpr, R.fields[k], scope); f[k] = enc(ok and v or nil) end
        n = n + 1; rows[n] = table.concat(f, "\29"); map[n] = s
        if R.sel and sel == nil then local ok, v = safe("sel", evalExpr, R.sel, scope); if ok and truthy(v) then sel = n - 1; self.selSlot = self.selSlot or {}; self.selSlot[L.list] = s end end
      end
    end
  else
    local src = self.env[L.from]
    local items = src
    if type(src) == "table" and type(src.data) == "table" then items = src.data end
    if type(items) ~= "table" then items = {} end
    local count = #items
    if L.max and count > L.max then count = L.max end
    for i = 1, count do
      local it = items[i]
      scope.it, scope.i = it, i
      if L.filter then local ok, keep = safe(id .. " filter", evalExpr, L.filter, scope); if ok and not truthy(keep) then it = nil end end
      if it ~= nil then
        local f = {}
        for k, fd in ipairs(L.fields) do
          local v
          if type(fd[2]) == "string" then v = type(it) == "table" and it[fd[2]] or nil
          else local ok, val = safe(id .. " " .. L.list .. "." .. fd[1], evalExpr, fd[2], scope); v = ok and val or nil end
          f[k] = enc(v)
        end
        n = n + 1; rows[n] = table.concat(f, "\29"); map[n] = i
        if L.sel and sel == nil then local ok, isSel = safe("sel", evalExpr, L.sel, scope); if ok and truthy(isSel) then sel = n - 1 end end
      end
    end
  end
  self.rowMaps = self.rowMaps or {}
  self.rowMaps[L.list] = map
  if L.tap then self.tapLists = self.tapLists or {}; self.tapLists[L.tap] = L end
  local sig = n .. "|" .. table.concat(rows, "\30")
  if self.last["@list:" .. L.list] ~= sig then
    self.last["@list:" .. L.list] = sig
    if G.perf then G.perf.lists = G.perf.lists + 1 end
    send("pc3d:ui:a:" .. self.id .. "|" .. L.list .. "|" .. sig)
  end
  if L.sel or L.rows then
    local ss = tostring(sel or -1)
    if self.last["@sel:" .. L.list] ~= ss then self.last["@sel:" .. L.list] = ss; send("pc3d:ui:sel:" .. self.id .. "|" .. L.list .. "|" .. ss) end
  end
end

--- Handles one native event of this screen (`kind` "tap" or "pan", `rest` its payload). A screen on its way out takes
--- no taps: it is leaving (its Back was tapped) or it has departed (its tap fired a screen change and its content slid
--- out; it takes taps again if no change came within 45 frames). A one-shot button (spec.leaveOn) makes its screen
--- leave at once after its handler ran: MatchSim's / MatchResults' Advance runs the caller's advance closure, and an
--- overlay that stayed up and tappable while the hub came back would take a second tap, run the advance again, send the
--- hub Back and close the Match Results it had just opened, leaving the game on a bare stock screen that takes no taps.
function Session:event(kind, rest)
  if kind == "tap" then
    if self.leaving then return end
    if self.departed then log("tap on " .. tostring(self.spec.id) .. " ignored: it is on its way out"); return end
  end
  local a0 = kind == "tap" and tostring(rest or ""):match("^([^:]+)") or nil
  if a0 then self.tapAct = a0 end
  self:dispatch(kind, rest)
  if a0 and self.spec.leaveOn and self.spec.leaveOn[a0] and not self.dead and not self.leaving then
    log(tostring(self.spec.id) .. " leaves after " .. a0 .. " (a one-tap button)")
    self:leaveNow()
  end
end

--- Routes a tap to the screen: list rows become the item / slot they stand for; the action then goes to a data-action
--- handler (list rows, aliases with an arg), a plain handler the screen registered, or the .dd's nav event.
--- A "pan" goes to the data action of the same name.
function Session:dispatch(kind, rest)
  local spec = self.spec
  if self.leaving then return end   -- on its way out (Back was tapped): no second tap reaches it
  if kind == "tap" then
    local action, row = rest:match("^([^:]+):?(%-?%d*)$")
    row = tonumber(row)
    if not action then return end
    -- list rows: native row -> the item / slot it came from
    local L = self.tapLists and self.tapLists[action]
    if L and row then
      local orig = self.rowMaps and self.rowMaps[L.list] and self.rowMaps[L.list][row + 1]
      if L.rows then
        if not orig then return end
        -- the card that is already open: a second tap enters it (the stock needs the separate Enter button)
        if L.tapSel and self.selSlot and self.selSlot[L.list] == orig and spec.actions and (self.handlers[L.tapSel] or spec.actions[L.tapSel]) then action = L.tapSel; row = nil; L = nil
        else action = action:gsub("#", tostring(orig)); row = nil end
      elseif orig then row = orig - 1 end
    end
    -- act_still3d: the empty control over a hub screen's 3D player (fc.hubPlayer3d) - it only keeps the touch from libpv's
    -- model rotation; nothing to run
    if action == "act_still3d" then return end
    local a = spec.actions and spec.actions[action]
    if G.logTaps ~= false then log("tap " .. tostring(spec.id) .. " " .. tostring(action) .. (row and (" row " .. tostring(row)) or "")) end
    -- An alias carries what the stock handler needs: data (a table, e.g. { buttonID = 1 }) or arg (a data-action index)
    local extra
    if a and a.alias then extra = a; action = a.alias; a = spec.actions[action] end
    -- array list rows behave like Zinc list items: the item's own data.clickAction (if it has one) is the action, and
    -- the handler gets { id = index0 }; rows without one are not tappable when the skin says so (rowTable)
    local rowData, itemArg
    if L and row and not L.rows then
      local src = self.env[L.from]
      local items = type(src) == "table" and type(src.data) == "table" and src.data or src
      local it = type(items) == "table" and items[row + 1] or nil
      local d = type(it) == "table" and (type(it.data) == "table" and it.data or it) or nil
      -- arg = "<field>": the data action gets that field of the tapped item (e.g. a club cell's team id)
      if a and type(a.arg) == "string" and d then itemArg = d[a.arg]; if itemArg == nil and type(it) == "table" then itemArg = it[a.arg] end end
      if d and d.clickAction ~= nil then
        if d.clickAction == "" or d.clickAction == false then return end
        action = tostring(d.clickAction); a = spec.actions and spec.actions[action] or a
      elseif a and a.rowTable then return end
      rowData = { id = row + (a and a.base or 0) }
    end
    local dh = (L and L.from and self.dataHandlersBy[tostring(L.from) .. "|" .. action]) or self.dataHandlers[action]
    -- The screen's .dd maps this action straight to a nav event (impl "nav"): the stock view fires that event and never
    -- calls a Lua handler of the same name (Search Players: act_search is evt_search -> the results; its Lua handler
    -- would fire an event no nav file knows).
    local ddNav = a and a.nav and not (dh and (row or (extra and extra.arg ~= nil)))
    if dh and not ddNav and (row or (extra and extra.arg ~= nil)) then
      local v
      if extra and extra.arg ~= nil then v = extra.arg elseif itemArg ~= nil then v = itemArg else v = row + (a and a.base or 0) end
      safe(spec.id .. " " .. action, dh.fn, dh.binding, action, v); return
    end
    local h = not ddNav and self.handlers[action]
    if h then
      -- plain buttons get no data (like Zinc), list rows get { id = index0 }, aliases their declared data
      safe(spec.id .. " " .. action, h, action, (extra and extra.data) or rowData)
      return
    end
    if dh and not ddNav then safe(spec.id .. " " .. action, dh.fn, dh.binding, action, row or 0); return end
    if a and a.nav then
      if spec.backEvents and spec.backEvents[a.nav] or a.nav == "evt_back" then G.dirBack = true; send("pc3d:ui:dir:back") end
      local wait = Skin.guestEvents[a.nav]
      if wait and self.nav and not G.pendingNav then
        -- a stock screen will open over this one: hide the native screens now (libpv frees its GPU memory), fire later
        Skin.guestHide("(opening " .. a.nav .. ")")
        G.pendingNav = { session = self, nav = a.nav, data = (extra and extra.data) or a.data, wait = wait }
        log("nav " .. tostring(spec.id) .. " -> " .. a.nav .. " in " .. wait .. " frames (a stock screen opens over the native ones)")
        return
      end
      -- through the screen's watched nav (depart, busy button), like a nav the screen's own Lua fires
      local nv = self.wnav or self.nav
      if nv then safe(spec.id .. " nav " .. a.nav, nv.Event, nil, a.nav, (extra and extra.data) or a.data) else log("no nav to fire " .. a.nav) end
      return
    end
    log("tap on " .. tostring(action) .. " has no handler in " .. tostring(spec.id))
  elseif kind == "pan" then
    local action, dx, dy = rest:match("^([^:]+):([%-%d%.e]+):([%-%d%.e]+)$")
    local dh = action and self.dataHandlers[action]
    if dh then safe(spec.id .. " pan", dh.fn, dh.binding, action, { panX = tonumber(dx) or 0, panY = tonumber(dy) or 0 }) end
  end
end

-- Screens waiting for an overlay they opened while being built come on with it (or when it fails).
local function releaseGates(except)
  for _, o in pairs(G.sessions) do
    if o ~= except and not o.dead and o.overlayGate then o.overlayGate = nil; o.readyWait = nil; o:goLive() end
  end
end
--- Sets the stock layout's two toggles (nil leaves one as it is): `native` = its touch blocker, `zinc` = its widgets.
--- The game builds the layout's view after the screen's constructor has returned, and keeps a value published before
--- that only for a binding the screen subscribed (the stock idiom: Subscribe, then Publish). So each toggle gets a
--- provider the first time, which hands the view the current value when it binds: without one, the "stock off" sent
--- from the constructor was lost and the stock layout stayed visible under the native screen (seen through popups,
--- the team picker and the in-match table).
function Session:toggles(native, zinc)
  local im = self.im
  if not im then return end
  local z = self.spec.zinc or {}
  local nb, zb = z.native or "bnd_prism_native", z.zinc or "bnd_prism_zinc"
  local t = self.tog
  if not t then
    t = {}
    self.tog = t
    for _, b in ipairs({ nb, zb }) do
      pcall(im.Subscribe, b, function() if t[b] ~= nil then pcall(im.Publish, b, t[b]) end end)
    end
  end
  if native ~= nil then t[nb] = native; pcall(im.Publish, nb, native) end
  if zinc ~= nil then t[zb] = zinc; pcall(im.Publish, zb, zinc) end
end

--- Ends the session and returns its screen to the stock layout (native off, Zinc on), e.g. when libpv refused the scene
--- or stopped answering. `reason` is logged by the caller.
function Session:fallback(reason)
  if self.dead then return end
  self.dead = true
  self:toggles(false, true)
  send("pc3d:ui:close:" .. self.id)
  G.sessions[self.id] = nil
  if G.cover == self then G.cover = nil end
  releaseGates(self)
  closeShellIfIdle()
end

--- A covering screen leaves at once (its Back was tapped): libpv plays its exit now, while the game still closes the
--- stock state behind it (Settings saves first); taps stop reaching it and the screens under it take touches again.
function Session:leaveNow()
  if self.dead or self.leaving then return end
  self.leaving = true
  if G.cover == self then G.cover = nil end
  send("pc3d:ui:leave:" .. self.id)
end

--- Hides the button whose tap fired a screen change (`act` = its tap action) so it cannot be tapped twice while the
--- next screen builds. skinc ANDs `__busy != '<action>'` into the visibility of every button outside list rows. The
--- button comes back when another screen comes on (an overlay it opened, or the screen that replaces this one when the
--- engine keeps this one), or after BUSY_FRAMES of this screen's own frames if nothing answered.
local BUSY_FRAMES = 240
function Session:setBusy(act)
  if self.dead then return end
  self.busy = 0
  self:onPublish("__busy", act)
  self:flush(false)
end
function Session:clearBusy()
  if not self.busy then return end
  self.busy = nil
  if not self.dead then self:onPublish("__busy", "") end
end

--- Hides the whole screen (its root: skinc ANDs `!__gone` into the root's visibility) when its own screen change was
--- fired from another layer: Match Sim's Advance takes Start Match back to the hub, Match Results' Advance reloads the
--- hub, a popup's Yes leaves the career. That screen would otherwise show again, stale, between the overlay leaving and
--- the next screen coming on; hidden, the room behind it shows instead, like a loading screen. If the screen is still
--- alive and ticking GONE_FRAMES later (no screen change came), it shows again.
local GONE_FRAMES = 150
function Session:setGone(on)
  if self.dead then return end
  if on then
    if self.gone then return end
    self.gone = 0
    log(tostring(self.spec.id) .. " hides: its screen change came from another layer")
  else
    if not self.gone then return end
    self.gone = nil
  end
  self:onPublish("__gone", on and true or false)
  self:flush(false)
end

--- Called when the main menu comes on: a career screen still alive then (one the engine left over the menu when the
--- career was left without its exit) is stopped and its native layer closed, so it cannot cover the menu or swallow its
--- touches. Cover / guest state goes with it. The menu's own native screen (R98: MainHub is a skin, and the menu calls
--- this from its constructor) is the session being built then, and stays.
function Skin.menuReset()
  local n = 0
  for _, x in pairs(G.sessions) do
    if not x.dead and x ~= G.building then
      n = n + 1
      log("menu: a career screen was still up (" .. tostring(x.spec.id) .. "): closed")
      safe("menu reset " .. tostring(x.spec.id), x.stop, x)
      send("pc3d:ui:close:" .. x.id)
    end
  end
  G.cover, G.inTap = nil, nil
  Skin.usePalette(Skin.outsidePalette())   -- the main menu is not a career's
  rawset(_G, "PRISM_HUB_TAB", nil)   -- a career left here starts on Central next time (src/patches/HubTab.patch.js)
  if (G.guests or 0) > 0 or G.guestHidden then G.guests = 0; G.guestInst = nil; G.guestWho = nil; Skin.guestShow("(menu)") end
  closeShellIfIdle()
  return n
end

--- Binds the session to the built screen instance `o`: toggles the stock layout off (native on), registers the Zinc
--- no-op action, publishes the first values and starts the transition once the screen's stock providers have run.
--- If every screen a guest covered is gone while the native screens are still hidden, they show again first.
function Session:attach(o)
  rawset(o, "__pskin", self)
  local z = self.spec.zinc or {}
  if G.guestHidden then
    local covered = false
    for _, x in pairs(G.sessions) do if x ~= self and not x.dead and x.underGuest then covered = true break end end
    if not covered and not self.spec.modal then
      -- Safety: the screens the guest covered are all gone and a new screen comes, so the career went on.
      log("guest " .. tostring(G.guestWho) .. ": every screen it covered is gone, a new one opens - the native screens show again")
      G.guests = 0; G.guestInst = nil; G.guestWho = nil
      Skin.guestShow("(stale)")
    end
  end
  -- a screen that opens while a guest has the native screens hidden stays stock until they show again
  self:toggles(not G.guestHidden, G.guestHidden and true or false)
  if z.noop and not self.handlers[z.noop] then pcall(self.im.RegisterAction, z.noop, function() end) end
  self:onPublish("__busy", "")
  self:onPublish("__gone", false)
  self:runProviders()
  self:flush(true)
  -- The transition starts once the first values are in. A stock provider that failed (it needs state the screen sets a
  -- frame later, e.g. the hub's tab restored from the last visit) is retried first, so the screen does not open on its
  -- defaults (the Central tab) and jump a frame later; at most 12 frames.
  if self.overlayGate then log(tostring(self.spec.id) .. " waits for the overlay it opened (both come on together)")
  elseif #self.providers == 0 then self:sendReady() else self.readyWait = 0 end
end

--- Tells libpv the screen's first values are in (the transition starts), and lets the other screens' busy buttons show.
function Session:sendReady()
  self.readyWait = nil
  releaseGates(self)
  self:goLive()
  for _, x in pairs(G.sessions) do if x ~= self then x:clearBusy() end end
  -- G.readyCount[spec id] = how many times each screen has come on natively (the career boot waits for its loading
  -- screen's count).
  G.readyCount = G.readyCount or {}
  G.readyCount[self.spec.id] = (G.readyCount[self.spec.id] or 0) + 1
end

--- Sends the ready that starts the screen's transition. libpv drops a layer opened with "wait" whose ready has not come
--- 3 s (real time) after its open, and the shell with it when no screen is left. After a match the engine keeps this
--- thread busy or stopped for longer than that (career processing, the save): the ready of the hub and of its Match
--- Results found nothing, and the hub's stock layout, its widgets hidden for the native screen, showed black until the
--- back key left the career (R98e). So the layer is opened again first when it may be gone: its open is 3 s or more
--- back (os.time: more than 2 s; 30 s with an R98e libpv, which keeps a waiting layer while this thread does not run),
--- or a poll found libpv without any screen.
function Session:goLive()
  if self.dead then return end
  local late = self.openWall ~= nil and wall() - self.openWall >= (G.waitLimit or 3)
  if late or self.lost then
    if not self:reopen(late and ("its ready comes " .. tostring(wall() - self.openWall) .. " s after its open") or "libpv has no screen open") then return end
  end
  self.lost, self.openWall, self.live = nil, nil, true
  send("pc3d:ui:ready:" .. self.id)
end

--- Opens the session's layer again under the same id (libpv replaces whatever is left of it, the shell is opened again
--- or kept) and sends every value and list again: the new scene has none of them. Not more than 3 times a session, then
--- the screen goes back to its stock layout; also when libpv refuses the scene. Returns true when the layer is open.
function Session:reopen(why)
  if self.dead then return false end
  self.reopens = (self.reopens or 0) + 1
  if self.reopens > 3 then log(tostring(self.spec.id) .. ": lost natively again (" .. why .. "), back to its stock layout"); self:fallback("lost natively"); return false end
  log(tostring(self.spec.id) .. " opens again natively (" .. why .. ")")
  local r, tok = self:sendOpen("wait")
  if type(r) == "string" and r:sub(-#tok - 1) == ":" .. tok and r:sub(1, 3) ~= "ok:" then
    local refused = r:match("^err:(.*):[^:]*$") or r
    log("native: " .. tostring(self.spec.id) .. " did not open again (" .. tostring(refused) .. ")")
    self:fallback(refused)
    return false
  end
  self.last = {}
  for k in pairs(G) do if type(k) == "string" and k:sub(1, 6) == "shell:" then G[k] = nil end end   -- the shell's values, if it went too
  self:flush(true)
  return true
end

--- Runs the stock Subscribe providers of the bindings the skin reads. A provider that fails is retried on the next
--- frames (up to 20 tries): it usually needs state the stock screen sets a little later (a selected row).
function Session:runProviders()
  local q = self.providers
  if #q == 0 then return end
  self.providers = {}
  for i = 1, #q do
    local b, fn, tries = q[i][1], q[i][2], q[i][3] or 0
    local ok = pcall(fn, b)
    if not ok then
      -- Stock providers often need state the screen sets a little later (a selected row): try again next frame.
      if tries < 20 then self.providers[#self.providers + 1] = { b, fn, tries + 1 }
      else local _, err = pcall(fn, b); log("provider " .. tostring(b) .. " of " .. tostring(self.spec.id) .. " keeps failing: " .. tostring(err)) end
    end
  end
end

-- The guest bookkeeping runs once per frame, from the session that owns it (or any live one): fires a delayed guest
-- navigation event, gives up on a stock screen that never announced itself, restores the native state after a guest.
local function guestTick(self)
  local pn = G.pendingNav
  if pn and (pn.session == self or pn.session.dead) then
    pn.wait = pn.wait - 1
    if pn.wait <= 0 then
      G.pendingNav = nil
      G.guestWait = 45   -- the stock screen must announce itself within 45 frames, or the native screens come back
      local s = pn.session.dead and self or pn.session
      safe(tostring(s.spec.id) .. " nav " .. pn.nav, s.nav.Event, nil, pn.nav, pn.data)
    end
  elseif G.guestWait and (G.guests or 0) == 0 then
    G.guestWait = G.guestWait - 1
    if G.guestWait <= 0 then G.guestWait = nil; Skin.guestShow("(no stock screen opened)") end
  end
  if G.restoreIn then
    G.restoreIn = G.restoreIn - 1
    if G.restoreIn <= 0 then G.restoreIn = nil; if not G.guestHidden then Skin.publishAll(true) end end
  end
end

--- The per-frame work of one session, called from the screen's update: guest bookkeeping, providers, flush, the ready /
--- overlay-gate / depart / busy / gone timers, then the shared poll.
function Session:frame()
  if self.dead then return end
  guestTick(self)
  self:runProviders()
  local P = G.perf
  local t0 = clock()
  self:flush(false)
  -- The gates count frames, and libpv waits 3 s of real time for a ready: after a match the engine runs this thread at a
  -- few frames a second, so a screen comes on 2 s after its open (os.time: 1 to 2 s) whatever the counts say.
  local due = self.openWall ~= nil and wall() - self.openWall >= 2
  if self.readyWait then self.readyWait = self.readyWait + 1; if #self.providers == 0 or self.readyWait >= 12 or due then self:sendReady() end end
  if self.overlayGate then
    self.overlayGate = self.overlayGate + 1
    if self.overlayGate > 45 or due then
      self.overlayGate = nil
      log(tostring(self.spec.id) .. ": its overlay did not come natively in " .. (due and "2 s" or "45 frames") .. ", shown alone")
      if #self.providers == 0 or due then self:sendReady() else self.readyWait = 0 end
    end
  end
  if self.departed then
    self.departed = self.departed + 1
    if self.departed > 45 then self.departed = nil; send("pc3d:ui:undepart:" .. self.id) end   -- still here: no screen change came
  end
  if self.busy then self.busy = self.busy + 1; if self.busy > BUSY_FRAMES then self:clearBusy() end end
  if self.gone then
    self.gone = self.gone + 1
    if self.gone > GONE_FRAMES then log(tostring(self.spec.id) .. " shows again: no screen change came"); self:setGone(false) end
  end
  local t1 = clock()
  pollAll()
  if P then P.flush = P.flush + (t1 - t0); P.poll = P.poll + (clock() - t1) end
end

--- Ends the session when its screen is finalized: flushes, tells libpv to leave (the scene stays up for a native
--- successor and is closed by libpv when none follows) and switches off the stock layout's touch blocker. `failed`: the
--- screen did not build natively, so its stock layout is shown (it was hidden for the native one).
function Session:stop(failed)
  if self.dead then return end
  self.dead = true
  if self.restoreBack then self.restoreBack(); self.restoreBack = nil end
  self:flush(false)
  -- Is another native screen alive to take over? If not (the next screen is a stock one) libpv does not keep this up.
  local solo = true
  for _, o in pairs(G.sessions) do if o ~= self and not o.dead then solo = false break end end
  log("leave " .. tostring(self.spec.id) .. (solo and " (no native successor)" or " (a native screen follows)"))
  send("pc3d:ui:leave:" .. self.id .. (solo and "|solo" or ""))
  G.sessions[self.id] = nil
  if G.cover == self then G.cover = nil end
  local z = self.spec.zinc or {}
  -- The full-screen touch blocker of the stock layout goes with the session: a layout that outlives its screen for a
  -- moment (a stock transition) must not cover what comes next or swallow its taps.
  self:toggles(false, failed and true or nil)
  if z.noop then pcall(self.im.UnregisterAction, z.noop) end
end

------------------------------------------------------------------------ guests (stock screens over native ones)
-- A guest is a stock screen that opens OVER native ones, which stay loaded (a parallel state of MainFlow, e.g. a screen
-- the hub keeps under it). The guest's VM calls PrismSkinGuest from its new / finalize (tools/skinstall.js adds the
-- call): while any guest is up the native layers are hidden (kept, not closed) and touches go to the game. The screens
-- under a guest have their touch blocker off and nothing of theirs shows on the stock side either (zinc off too): their
-- stock layouts are drawn over the guest, so the hub's own Back button (act_exit, the same corner as the guest's Back)
-- would take the tap meant for the guest.

--- Publishes the native / zinc toggle bindings of every live session (`zinc` defaults to `not native`).
function Skin.publishAll(native, zinc)
  if zinc == nil then zinc = not native end
  for _, s in pairs(G.sessions) do
    if not s.dead and s.im then s:toggles(native, zinc) end
  end
end
--- Hides the native screens and shows the stock ones under them while guest `who` is up.
function Skin.guestHide(who)
  if G.guestHidden then return end
  G.guestHidden = true; G.restoreIn = nil
  for _, s in pairs(G.sessions) do if not s.dead then s.underGuest = true end end
  send("pc3d:ui:hide"); Skin.publishAll(false, false)
  log("guest " .. tostring(who) .. ": the native screens hide, the stock screens under them show")
end
--- Closes the guest that is up the way its own Back does (Settings: quitAndRevert -> evt_exit_settings_customize).
--- Returns false when there is no guest instance or it has no close method.
function Skin.guestClose()
  local o = G.guestInst
  if type(o) ~= "table" then return false end
  for _, m in ipairs({ "quitAndRevert", "close", "goBack" }) do
    if type(o[m]) == "function" then safe("guest close", o[m], o); return true end
  end
  return false
end
--- Shows the native screens again after a guest closed.
function Skin.guestShow(who)
  if not G.guestHidden then return end
  G.guestHidden = false; G.guestWait = nil
  for _, s in pairs(G.sessions) do s.underGuest = nil end
  send("pc3d:ui:show")
  G.restoreIn = 1    -- the stock side under a guest is empty, so the screens take their native state at once
  log("guest " .. tostring(who) .. " closed: the native screens show again")
end
--- Global hook called by the guest code that skinstall adds to a guest screen's VM: PrismSkinGuest(1, who) when the
--- guest is created, (0, who, instance) once it is built, (-1, who, instance) when it closes (counted once per
--- instance).
pcall(rawset, _G, "PrismSkinGuest", function(d, who, inst)
  if d == 0 then if type(inst) == "table" then G.guestInst = inst end return end   -- the instance, once it is built
  G.guests = math.max(0, (G.guests or 0) + (d or 0))
  if G.guests > 0 then G.guestWho = who; G.guestWait = nil; Skin.guestHide(who .. " opens")
  elseif G.guests == 0 then G.guestInst = nil; G.guestWho = nil; G.pendingNav = nil; Skin.guestShow(who) end
end)

------------------------------------------------------------------------ wrap
--- Returns a subclass of the stock screen class `Class` that draws through Prism Native according to `spec` (see the
--- header). `theme` (PrismTheme.lua) defaults to spec.theme. The subclass's new() opens the native scene, wraps `init`,
--- builds the stock screen, then runs spec.model and attaches the session; update() runs the session's frame and
--- finalize() stops it. Without a usable native layer it builds the stock screen unchanged. Spec members used here:
---   when(init) -> bool       false: this instance stays stock (Settings opened from a paused match)
---   model(session, o, init)  the skin's own data (bindings it publishes into the session, handlers for its own
---                            actions) on top of the stock VM's; a model that fails or returns false leaves the
---                            screen on its stock layout
---   cover                    this screen covers the others while it is up (see the guarded actions in wrapInit)
---   salvage                  the stock constructor builds on the `init` table it is given, so when it throws half way
---                            the half-built instance carries on natively (the stock screen always lived with that error:
---                            Settings on a game whose settings service lacks a call the constructor makes)
function Skin.wrap(Class, spec, theme)
  if type(Class) ~= "table" or type(Class.new) ~= "function" or type(spec) ~= "table" or not spec.scene then
    log("wrap: not applied (class " .. type(Class) .. ", spec " .. type(spec) .. ", scene " .. tostring(type(spec) == "table" and spec.scene) .. ")")
    return Class
  end
  local Sub = setmetatable({}, { __index = Class })
  Sub.__index = Sub
  Sub.__prismSkin = spec.id
  function Sub.new(selfW, init)
    local s
    local want = true
    if type(spec.when) == "function" then local okw, w = pcall(spec.when, init); want = okw and w and true or false; if not want then log("wrap: " .. tostring(spec.id) .. " stays stock here") end end
    if want and type(init) == "table" and init.im and spec.native ~= false and not G.offScreens[spec.id] then
      local ok, ready = safe("PrismSkin hello", hello, init.api)
      if not (ok and ready) then log("wrap: " .. tostring(spec.id) .. " stock layout (hello ok=" .. tostring(ok) .. " ready=" .. tostring(ready) .. " off=" .. tostring(G.off) .. ")") end
      if ok and ready then
        -- an inline screen (Settings) is not handed the theme: it takes the one already in use, or PrismTheme's global
        local th = theme or spec.theme or G.theme or rawget(_G, "PRISM_THEME")
        sendTheme(th)
        -- the user's league palette in a career, FC27's green elsewhere
        G.theme = th
        safe("palette", Skin.usePalette, Skin.userPalette(th), th)
        s = newSession(spec, init)
        if not s:open() then s = nil else init = s:wrapInit(init) end
      end
    end
    if not s and (type(init) ~= "table" or not init.im or G.offScreens[spec.id]) then
      log("wrap: " .. tostring(spec.id) .. " skipped (init " .. type(init) .. ", im " .. tostring(type(init) == "table" and init.im ~= nil) .. ", off " .. tostring(G.offScreens[spec.id] or G.off) .. ")")
    end
    G.building = s
    local okNew, o = xpcall(function() return Class.new(Sub, init) end, traceback)
    G.building = nil
    if not okNew then
      log("new of " .. tostring(spec.id) .. " failed: " .. tostring(o))
      if s and spec.salvage and type(init) == "table" and getmetatable(init) == Sub then
        -- the stock constructor had set the instance up (its metatable is ours) before it threw: the screen goes on
        log(tostring(spec.id) .. ": goes on with the instance the stock constructor had built")
        o, okNew = init, true
        rawset(o, "__salvaged", true)
      else
        if s then s:stop(true) end
        error(o, 0)
      end
    end
    if s and type(o) == "table" and type(spec.model) == "function" then
      local okM, err = pcall(spec.model, s, o, init)
      if not okM or err == false then log("model of " .. tostring(spec.id) .. (okM and " declined" or (" failed: " .. tostring(err))) .. ": stock layout"); s:fallback("model"); s = nil end
    end
    if s then
      if type(o) == "table" then
        if spec.cover then G.cover = s; for _, x in pairs(G.sessions) do if x ~= s and not x.dead then x.underCover = s end end end
        s:attach(o)
      else s:stop(true) end
    end
    -- Prism Workers: the screen adapters registered with PrismJobs.adapter move this screen's background work to
    -- libpv's worker threads.
    local J = rawget(_G, "PrismJobs")
    if J and type(o) == "table" and type(J.attach) == "function" then safe("PrismJobs attach " .. tostring(spec.id), J.attach, spec.id, o, s and s.id or nil, type(init) == "table" and init.api or nil) end
    return o
  end
  function Sub.update(self, dt, ...)
    local r
    local t0 = clock()
    if Class.update then r = Class.update(self, dt, ...) end
    local J = rawget(_G, "PrismJobs")
    if J and J.poll then safe("PrismJobs poll", J.poll) end
    local s = type(self) == "table" and rawget(self, "__pskin")
    if s then
      local t1 = clock()
      safe("PrismSkin frame", s.frame, s)
      local t2 = clock()
      local P = G.perf
      if not P then P = { n = 0, stock = 0, skin = 0, at = t2, pub = 0, vals = 0, lists = 0, cmds = 0, poll = 0, flush = 0 }; G.perf = P end
      P.n = P.n + 1; P.stock = P.stock + (t1 - t0); P.skin = P.skin + (t2 - t1)
      if t2 - P.at >= 5 and P.n > 0 then
        log(string.format("perf: %d frames, process cpu per frame while in the Lua update (os.clock counts every thread): stock update %.2f ms, skin %.2f ms (poll %.2f, flush %.2f); per frame: %.1f publishes, %.1f values sent, %.2f lists sent, %.2f commands; %d polls, seq %s..%s",
          P.n, P.stock * 1000 / P.n, P.skin * 1000 / P.n, P.poll * 1000 / P.n, P.flush * 1000 / P.n, P.pub / P.n, P.vals / P.n, P.lists / P.n, P.cmds / P.n, P.reads or 0, tostring(P.seqLo), tostring(P.seqHi)))
        P.n, P.stock, P.skin, P.at, P.pub, P.vals, P.lists, P.cmds, P.poll, P.flush, P.reads, P.seqLo, P.seqHi = 0, 0, 0, t2, 0, 0, 0, 0, 0, 0, 0, nil, nil
      end
    end
    return r
  end
  function Sub.finalize(self, ...)
    local s = type(self) == "table" and rawget(self, "__pskin")
    if s then safe("PrismSkin stop", s.stop, s) end
    local J = rawget(_G, "PrismJobs")
    if J and type(J.detach) == "function" then safe("PrismJobs detach", J.detach, spec.id, self) end
    -- a salvaged instance lacks what the stock constructor did not reach: its finalize must not take the unload down
    if Class.finalize and type(self) == "table" and rawget(self, "__salvaged") then return safe(tostring(spec.id) .. " finalize", Class.finalize, self, ...) end
    if Class.finalize then return Class.finalize(self, ...) end
  end
  return Sub
end

return Skin
