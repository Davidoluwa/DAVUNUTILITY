-- the translator (a copy of runtime/PrismI18n.lua)
local function translator()
--[[ PrismI18n.lua - the display translation of a language variant (src/variants/pt-BR).

Every string that PrismSkin sends to the native screens goes through tr() (PrismSkin.enc), so the values the game and the
screens compare and branch on stay as the game made them and only what the player reads changes. Static texts of the
scenes (.pn) are translated at install time by the variant's post.js with the same tables.

The tables come from PrismI18nData.lua (built by the variant's generate.js from src/variants/<name>/i18n/*.json):
  exact      { ["Advance"] = "Avançar", ... }                      the whole string
  templates  { { "{1} completes {2} move to {3}", "{1} fecha ..." } }   a sentence with placeholders; {n} is whatever the
                                                                    game put there (a name, a fee), {tn} the same translated
  words      { ["August"] = "agosto", ... }                        month / weekday names, replaced inside a date-like string
                                                                    (one with a digit)
  ordinal    "%dº"                                                 1ST 2ND 3RD 4TH ... on their own

tr(s) returns s itself for everything it has no entry for (names, numbers, amounts). Results are remembered, so a string
is worked out once. With PRISM_I18N.record = true every string with letters that found no entry is counted in
PRISM_I18N.missing (the coverage run of src/variants/pt-BR/tests/test_i18n_coverage.py filters names out of it).
The tables are read on the first tr() call, not when this file loads (R98d): the phone's engine does not promise to run
PrismI18nData.lua first, and a translator built before its data stayed empty for the whole session (every dynamic text
English). tr() also picks up a newer PRISM_I18N_DATA. PrismI18nData.lua carries a copy of this file too, so either module
alone is enough.
]]
local M = rawget(_G, "PRISM_I18N") or {}
rawset(_G, "PRISM_I18N", M)

local exact, words, ordinal = {}, {}, "%1º"
local memo, nmemo = {}, 0
local built, nbuilt = nil, 0
M.missing = M.missing or {}

-- templates: "{1} completes {2}" -> an anchored Lua pattern and the capture order of the target
local function compile(en, pt)
  local pat, n = {}, 0
  local last = 1
  for s, num, e in en:gmatch("(){t?(%d)}()") do
    pat[#pat + 1] = en:sub(last, s - 1):gsub("[%^%$%(%)%%%.%[%]%*%+%-%?]", "%%%0")
    pat[#pat + 1] = "(.-)"
    n = n + 1
    last = e
  end
  pat[#pat + 1] = en:sub(last):gsub("[%^%$%(%)%%%.%[%]%*%+%-%?]", "%%%0")
  return { pat = "^" .. table.concat(pat) .. "$", pt = pt, n = n }
end
local byChar, any = {}, {}

--- (Re)builds the lookups from the data table D (PRISM_I18N_DATA).
local function build(D)
  exact, words, ordinal = D.exact or {}, D.words or {}, D.ordinal or "%1º"
  byChar, any = {}, {}
  for _, t in ipairs(D.templates or {}) do
    local c = compile(t[1], t[2])
    local lead = t[1]:sub(1, 1)
    if lead == "{" or lead == "" then any[#any + 1] = c else
      byChar[lead] = byChar[lead] or {}
      table.insert(byChar[lead], c)
    end
  end
  nbuilt = 0
  for _ in pairs(exact) do nbuilt = nbuilt + 1 end
  memo, nmemo = {}, 0
  built = D
end

--- The lookups follow the data the game has now: built on first use, again when PRISM_I18N_DATA is another table.
local function ready()
  local D = rawget(_G, "PRISM_I18N_DATA")
  if D ~= built and type(D) == "table" then build(D) end
end

local tr
local function fill(c, caps)
  return (c.pt:gsub("{(t?)(%d)}", function(t, d)
    local v = caps[tonumber(d)]
    if v == nil then return "" end
    if t == "t" then return tr(v) end
    return v
  end))
end

local function viaTemplates(s)
  local list = byChar[s:sub(1, 1)]
  if list then
    for i = 1, #list do
      local c = list[i]
      local caps = { s:match(c.pat) }
      if caps[1] ~= nil or (c.n == 0 and s:find(c.pat)) then return fill(c, caps) end
    end
  end
  for i = 1, #any do
    local c = any[i]
    local caps = { s:match(c.pat) }
    if caps[1] ~= nil then return fill(c, caps) end
  end
end

--- Upper case for the Latin-1 letters Lua's own upper() leaves alone (UTF-8: a-grave .. thorn, not the division sign).
local function upper(s)
  return (s:upper():gsub("\195([\160-\190])", function(c)
    if c == "\183" then return nil end
    return "\195" .. string.char(c:byte() - 32)
  end))
end

-- "SAT, AUG 22" style: month and weekday names inside a string that has a number
local function viaWords(s)
  if not s:find("%d") then return nil end
  local changed = 0
  local out = s:gsub("%a+", function(w)
    local x = words[w] or words[w:sub(1, 1):upper() .. w:sub(2):lower()]
    if x then
      if w == w:upper() and #w > 1 then x = upper(x) end
      changed = changed + 1
      return x
    end
  end)
  if changed > 0 then return out end
end

-- Dates the game writes in English order, put in Portuguese order: "Sun, April 7" -> "dom, 7 de abril", "22 August 2026" /
-- "August 22, 2026" -> "22 de agosto de 2026", "August 22" -> "22 de agosto". Full month names take "de", abbreviations
-- ("Aug 22" -> "22 ago") do not.
local FULL = { January = 1, February = 1, March = 1, April = 1, May = 1, June = 1, July = 1, August = 1, September = 1, October = 1, November = 1, December = 1 }
local function title(w) return w:sub(1, 1):upper() .. w:sub(2):lower() end
local function month(w)
  local k = title(w)
  if words[k] and (FULL[k] or k == "Jan" or k == "Feb" or k == "Mar" or k == "Apr" or k == "Jun" or k == "Jul" or k == "Aug" or k == "Sep" or k == "Sept" or k == "Oct" or k == "Nov" or k == "Dec") then
    return words[k], FULL[k] and true or false
  end
end
local function viaDates(s)
  local wd, mo, d, y = s:match("^(%a+), (%a+) (%d+)$")
  local form
  if wd then form = 1 else
    d, mo, y = s:match("^(%d+) (%a+) (%d%d%d%d)$")
    if d then form = 2 else
      mo, d, y = s:match("^(%a+) (%d+),? (%d%d%d%d)$")
      if mo then form = 3 else
        mo, d = s:match("^(%a+) (%d+)$")
        if mo then form = 4 end
      end
    end
  end
  if not form then return nil end
  local m, full = month(mo)
  if not m then return nil end
  local day = (words[title(wd or "")] or nil)
  if form == 1 and not day then return nil end
  local out = d .. (full and " de " or " ") .. m
  if y then out = out .. (full and " de " or " ") .. y end
  if day then out = day .. ", " .. out end
  if s == s:upper() then out = upper(out) end
  return out
end

local function viaOrdinal(s)
  local n, suffix = s:match("^(%d+)([SsNnRrTt][TtDdHh])$")
  if n then
    local u = suffix:upper()
    if u == "ST" or u == "ND" or u == "RD" or u == "TH" then return (ordinal:gsub("%%1", n)) end
  end
end

local function work(s)
  local x = exact[s]
  if x then return x end
  if #s < 3 then return s end
  x = viaOrdinal(s) or viaTemplates(s) or viaDates(s) or viaWords(s)
  if x then return x end
  -- an all-capitals text (the game shouts some labels: "HOME KIT"): the entry of its Title Case form, in capitals
  if s == s:upper() and s:find("%a%a") then
    local tc = s:lower():gsub("(%a)(%a*)", function(a, b) return a:upper() .. b end)
    if exact[tc] then return upper(exact[tc]) end
  end
  -- a popup or a card text the game wrapped (Utils.formatString / UI:formatString turn spaces into line breaks): looked up
  -- again with its white space collapsed, which is how the tables list it
  if s:find("\n", 1, true) then
    local u = s:gsub("%s+", " ")
    if u ~= s then
      x = M.tr(u)
      if x ~= u then return x end
    end
  end
  -- a leading / trailing space or a trailing colon around a known text ("Club:" "Age ")
  local core, tail = s:match("^(.-)([:%s]*)$")
  if core ~= s and core ~= "" and exact[core] then return exact[core] .. tail end
  if M.record and s:find("%a%a%a") then M.missing[s] = (M.missing[s] or 0) + 1 end
  return s
end

--- The translation of s (s itself when there is none).
function M.tr(s)
  ready()
  local r = memo[s]
  if r ~= nil then return r end
  r = work(s)
  if nmemo > 6000 then memo, nmemo = {}, 0 end
  memo[s] = r; nmemo = nmemo + 1
  return r
end
