"""Generate src/unicode_data.h: codepoint ranges tagged with the classes the Flint
pre-tokenizer regex needs. Run with the system Python: python3 -I tools/gen_unicode.py"""
import sys
import unicodedata

# Category codes stored in the low 4 bits; bit 4 marks Unicode White_Space.
CAT = {"Lu": 1, "Ll": 2, "Lt": 3, "Lm": 4, "Lo": 5, "Mn": 6, "Mc": 6, "Me": 6,
       "Nd": 7, "Nl": 7, "No": 7,
       "Pc": 8, "Pd": 8, "Ps": 8, "Pe": 8, "Pi": 8, "Pf": 8, "Po": 8,
       "Sm": 9, "Sc": 9, "Sk": 9, "So": 9}
WHITE_SPACE = set(range(0x09, 0x0E)) | {0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000} \
    | set(range(0x2000, 0x200B))


def code(cp):
    c = CAT.get(unicodedata.category(chr(cp)), 0)
    return c | (16 if cp in WHITE_SPACE else 0)


ranges = []
prev = None
for cp in range(0x110000):
    c = code(cp)
    if c != prev:
        ranges.append((cp, c))
        prev = c

out = sys.argv[1] if len(sys.argv) > 1 else "src/unicode_data.h"
with open(out, "w") as f:
    f.write("// Generated by tools/gen_unicode.py from Python unicodedata "
            f"(Unicode {unicodedata.unidata_version}). Do not edit.\n")
    f.write("// Each entry: first codepoint of a run, class code for the run.\n")
    f.write("// Class: 0 other, 1 Lu, 2 Ll, 3 Lt, 4 Lm, 5 Lo, 6 M, 7 N, 8 P, 9 S; +16 = White_Space.\n")
    f.write("#pragma once\n#include <cstdint>\n\nnamespace fl {\n")
    f.write(f"static const uint32_t k_ucd_start[{len(ranges)}] = {{\n")
    for i in range(0, len(ranges), 12):
        f.write("    " + ", ".join(f"0x{r[0]:X}" for r in ranges[i:i + 12]) + ",\n")
    f.write("};\n")
    f.write(f"static const uint8_t k_ucd_class[{len(ranges)}] = {{\n")
    for i in range(0, len(ranges), 32):
        f.write("    " + ", ".join(str(r[1]) for r in ranges[i:i + 32]) + ",\n")
    f.write("};\n}  // namespace fl\n")
print(f"{len(ranges)} ranges, Unicode {unicodedata.unidata_version} -> {out}")
